"""Writes apps/edge/src/site-shell.ts: the website frame (head, header, footer) as strings, for the pages the server code generates (the Trust page).
The frame is the same one build_pages.py puts on every other page, so the Trust page looks like the rest of the site.

    python -I tools/site-brand/write_edge_shell.py        (from the repository root)
then: bun run tools/make-trust.ts"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import shell

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(ROOT, "apps", "edge", "src", "site-shell.ts")

head = shell.head("@@TITLE@@", "@@DESC@@", "@@PATH@@", plain=True)
luck_symbol = re.search(r'<symbol id="i-luck".*?</symbol>', shell.sprite(), re.S).group(0)
sprite = f'<svg class="ck-sprite" width="0" height="0" aria-hidden="true" focusable="false"><defs>{luck_symbol}</defs></svg>'
top = sprite + "\n" + shell.header("")
foot = shell.footer()

ts = f"""// GENERATED by tools/site-brand/write_edge_shell.py from the Corporate Games brand kit. Do not edit by hand: change the generator and run it again.
// The website frame (head, six-item header, footer) for the pages the server writes itself (the Trust page), so they look like every other page of the site.
const HEAD = {json.dumps(head, ensure_ascii=False)};
const TOP = {json.dumps(top, ensure_ascii=False)};
const FOOT = {json.dumps(foot, ensure_ascii=False)};
const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** A whole page: the frame around main (the html of a <main id="main" class="ck-doc"> block). */
export function shellPage(title: string, desc: string, path: string, main: string): string {{
  const head = HEAD.split("@@TITLE@@").join(esc(title)).split("@@DESC@@").join(esc(desc)).split("@@PATH@@").join(path);
  return head + "\\n" + TOP + main + "\\n" + FOOT + "\\n</body></html>\\n";
}}
"""
with open(OUT, "w", encoding="utf8", newline="\n") as f:
    f.write(ts)
print("wrote", OUT, len(ts))
